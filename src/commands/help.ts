// /help — что умеет бот и список команд.

import type { TelegramMessage } from "../types";
import { sendMessage } from "../lib/telegram";
import { appKeyboard } from "../lib/urls";

const HELP =
	"ℹ️ <b>Книжный клуб — помощь</b>\n\n" +
	"<b>Карточки</b>\n" +
	"Повторение — в приложении клуба: добавь книги в колоду и отвечай, " +
	"насколько легко вспомнил, — интервалы подберёт алгоритм SM-2. " +
	"Колода, прогресс и статистика общие для приложения и бота.\n" +
	"Я напоминаю в 10:00 МСК, когда в колоде есть карточки к повторению.\n" +
	"/today — что сейчас ждёт повторения\n" +
	"/status — твоя статистика\n" +
	"/stop — выключить напоминания, /start — включить\n\n" +
	"<b>Доклады</b>\n" +
	"/speaker — выступить с докладом: участникам клуба — выбор темы из плана, " +
	"новым — заявка на участие\n" +
	"/cancel — прервать заявку\n\n" +
	"<b>Встречи</b>\n" +
	"Запись на встречи и план — в приложении клуба; заявку и выбор темы можно оформить и там.\n\n" +
	"<b>Для админов</b>\n" +
	"/anons_here — подключить чат к постам о встречах (отправить в группе клуба)\n" +
	"/anons_stop — отключить посты в этом чате\n\n" +
	"/help — показать это сообщение";

export async function handleHelp(env: Env, message: TelegramMessage): Promise<void> {
	await sendMessage(env.BOT_TOKEN, message.chat.id, HELP, appKeyboard(env, "🗂 Открыть приложение"));
}
