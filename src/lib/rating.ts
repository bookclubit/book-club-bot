/**
 * Рейтинг тем: доля «полезно» с поправкой на число оценок.
 *
 * Почему не средний процент: у темы с одной оценкой «полезно» он равен 100% —
 * она бы обгоняла тему с 20 оценками и 95%. Нижняя граница доверительного
 * интервала Уилсона (95%) решает это без ручных костылей: пока оценок мало,
 * она сильно ниже наблюдаемой доли, и с ростом числа оценок подтягивается к ней.
 * Тот же приём используют Reddit и Hacker News.
 */

/** Тема попадает в рейтинг, начиная с этого числа оценок. */
export const MIN_RATING_VOTES = 3;

/** z для 95% доверительного интервала. */
const Z = 1.959964;

/**
 * Нижняя граница доли «полезно» (0…1). Без оценок — 0.
 * Оценки «не очень» тянут её вниз, поэтому рейтинг не сводится к числу лайков.
 */
export function wilsonScore(up: number, down: number): number {
	const n = up + down;
	if (n <= 0) return 0;
	const p = up / n;
	const z2 = Z * Z;
	const denominator = 1 + z2 / n;
	const centre = p + z2 / (2 * n);
	const margin = Z * Math.sqrt((p * (1 - p)) / n + z2 / (4 * n * n));
	return Math.max(0, (centre - margin) / denominator);
}
